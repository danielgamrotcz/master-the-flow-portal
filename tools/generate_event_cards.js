// NODE_PATH=<stávající instalace Playwright> node tools/generate_event_cards.js
// Deterministický render lokální HTML/CSS šablony. Žádná síť ani cloudové zápisy.
const fs = require('fs');
const path = require('path');
const { createHash } = require('crypto');
const { chromium } = require('playwright');
const { ORIGIN, projectEvent, escapeHtml: esc } = require('./event-card-model.js');
const ROOT = path.resolve(__dirname, '..');
const font = name => fs.readFileSync(path.join(ROOT, 'fonts', `IBMPlexSans-${name}.woff2`)).toString('base64');
const fontCss = ['Regular', 'SemiBold', 'Bold'].map((name, i) =>
  `@font-face{font-family:Plex;src:url(data:font/woff2;base64,${font(name)}) format('woff2');font-weight:${[400, 600, 700][i]}}`).join('');

function cardHtml(card) {
  return `<!doctype html><html lang="cs"><head><meta charset="utf-8"><style>
  ${fontCss}
  *{box-sizing:border-box}body{margin:0;background:#faf6f2;color:#171411;font-family:Plex,sans-serif}
  main{width:1200px;height:630px;padding:54px 64px;display:flex;flex-direction:column}
  header{font-size:28px;font-weight:600;letter-spacing:-1px}header span{color:#b84d0a}
  .body{flex:1;display:flex;flex-direction:column;justify-content:center;padding-top:12px}
  .label{font-size:20px;letter-spacing:2px;font-weight:600;color:#6f6259;margin-bottom:22px}
  h1{font-size:88px;line-height:1.05;font-weight:700;letter-spacing:-3.5px;margin:0}
  h1 span{display:block;white-space:nowrap}h1 span:last-child{color:#b84d0a}
  .subtitle{font-size:32px;line-height:1.25;margin:22px 0 0;color:#4b413a}
  footer{border-top:1px solid #d9cdc3;padding-top:23px;display:flex;justify-content:space-between;font-size:23px}
  .domain{color:#6f6259;font-size:21px}
  </style></head><body><main><header>Master the <span>Flow</span></header>
  <div class="body"><div class="label">${esc(card.label)}</div>
  <h1>${card.lines.map(line => `<span>${esc(line)}</span>`).join('')}</h1>
  ${card.subtitle ? `<p class="subtitle">${esc(card.subtitle)}</p>` : ''}</div>
  <footer><span>${esc(card.date)}${card.time ? ' · ' + esc(card.time) : ''}</span><span class="domain">mastertheflow.cz</span></footer>
  </main></body></html>`;
}

function meta(card, version) {
  const image = `${ORIGIN}${card.imagePath}?v=${version}`;
  const desc = card.description || `${card.label} · ${card.date}${card.time ? ' · ' + card.time : ''} · Master the Flow`;
  return `  <!-- event-preview:start (generated by tools/generate_event_cards.js) -->
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="Master the Flow">
  <meta property="og:locale" content="cs_CZ">
  <meta property="og:title" content="${esc(card.title)}">
  <meta property="og:description" content="${esc(desc)}">
  <meta property="og:url" content="${ORIGIN}${card.pagePath}">
  <meta property="og:image" content="${image}">
  <meta property="og:image:type" content="image/png">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:image:alt" content="${esc(card.title)} · ${esc(card.date)}">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${esc(card.title)}">
  <meta name="twitter:description" content="${esc(desc)}">
  <meta name="twitter:image" content="${image}">
  <meta name="twitter:image:alt" content="${esc(card.title)} · ${esc(card.date)}">
  <link rel="canonical" href="${ORIGIN}${card.pagePath}">
  <!-- event-preview:end -->`;
}

function updateLanding(html, metadata) {
  // Jen metadata; body, registrační odkazy a skripty zůstanou nedotčené.
  const parts = html.split('</head>');
  if (parts.length !== 2) throw new Error('Expected one document head');
  let head = parts[0].replace(/^[ \t]*<!-- event-preview:start[^]*?<!-- event-preview:end -->\n?/m, '');
  head = head.replace(/^[ \t]*<meta\b[^>]*(?:property="og:[^"]*"|name="twitter:[^"]*")[^>]*>\n?/gm, '')
    .replace(/^[ \t]*<link\b[^>]*rel="canonical"[^>]*>\n?/gm, '');
  return `${head}${metadata}\n</head>${parts[1]}`;
}

function sharePage(card, metadata) {
  return `<!DOCTYPE html>
<!-- Generated by tools/generate_event_cards.js; public fields only. -->
<html lang="cs"><head><meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="theme-color" content="#faf6f2">
  <title>${esc(card.title)} | Master the Flow</title>
${metadata}
  <link rel="stylesheet" href="/event-cards/share.css">
  <link rel="icon" type="image/svg+xml" href="/favicon.svg">
</head><body><main>
  <h1>${esc(card.title)}</h1>
  <img src="${card.imagePath}" width="1200" height="630" alt="${esc(card.title)} · ${esc(card.date)}">
  <a href="/#event/${card.id}">Otevřít detail v portálu</a>
  <p>Komunitní portál může vyžadovat přístupový kód.</p>
</main></body></html>
`;
}

async function generate() {
  const events = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/events.json'), 'utf8')).events;
  // Validate all inputs before the first output; no partial catalog on missing design.
  const cards = events.map(projectEvent);
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1200, height: 630 }, deviceScaleFactor: 1 });
    await page.route('**/*', route => route.abort());
    fs.mkdirSync(path.join(ROOT, 'event-cards'), { recursive: true });
    for (const card of cards) {
      await page.setContent(cardHtml(card));
      await page.evaluate(() => document.fonts.ready);
      const fits = await page.evaluate(() => [...document.querySelectorAll('h1 span,.subtitle')].every(el => {
        const r = el.getBoundingClientRect();
        return el.scrollWidth <= el.clientWidth && r.bottom < document.querySelector('footer').getBoundingClientRect().top - 12;
      }));
      if (!fits) throw new Error(`Card text overflows: ${card.id}`);
      const png = await page.screenshot({ type: 'png' });
      const version = createHash('sha256').update(png).digest('hex').slice(0, 12);
      fs.writeFileSync(path.join(ROOT, card.imagePath), png);
      const target = path.join(ROOT, card.pagePath, 'index.html');
      if (card.landing) {
        fs.writeFileSync(target, updateLanding(fs.readFileSync(target, 'utf8'), meta(card, version)));
      } else {
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.writeFileSync(target, sharePage(card, meta(card, version)));
      }
      console.log(`Generated ${card.id}: ${card.pagePath}`);
    }
  } finally { await browser.close(); }
}

if (require.main === module) generate().catch(error => { console.error(error.message); process.exitCode = 1; });
module.exports = { cardHtml, meta, updateLanding, sharePage };
