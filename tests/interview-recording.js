// Permanent contract: public recording resources and backwards-compatible safe link labels.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'data/events.json'), 'utf8'));
const event = data.events.find(e => e.id === 'evt-2026-10-21-vibe-coding-nezacina-promptem');
const source = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const context = { URL, esc: s => String(s).replace(/[&<>"']/g, x => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[x])) };
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function renderCardLinks(card) {'), source.indexOf('/* ===== OBRÁZKY')), context);
assert.match(context.renderCardLinks({links:['https://www.example.com/a', 'https://www.example.com/a']}), />example.com<\/a>/);
assert.equal((context.renderCardLinks({links:['https://www.example.com/a', 'https://www.example.com/a']}).match(/<a /g)||[]).length, 1);
assert.equal(context.renderCardLinks({links:[null,{},42,'javascript:alert(1)',{url:'data:text/html,x'},'https://']}), '');
const injection = context.renderCardLinks({links:[{url:'https://example.com/?x=" onmouseover="x',label:'<img src=x onerror=alert(1)>'}]});
assert.ok(!injection.includes('<img'));
assert.ok(injection.includes('&lt;img'));
assert.ok(!injection.includes('href="https://example.com/?x="'));
assert.equal(event.registration_url, null);
assert.equal(event.registration_page_url, null);
assert.equal(event.status, 'Proběhlo');
assert.equal(event.is_paid, false);
assert.equal(event.recording_url, 'https://www.youtube.com/watch?v=SQ4VtvYf8E4');
const resources = context.renderCardLinks(event);
for(const label of ['Alexovy materiály','Časovaný přepis','Přepis ke stažení (TXT)']) assert.ok(resources.includes(label));
for(const link of event.links) assert.ok(fs.existsSync(path.join(root,new URL(link.url).pathname)));
const landing=fs.readFileSync(path.join(root,event.detail_url,'index.html'),'utf8');
assert.ok(!landing.includes('Záznam připravujeme'));
assert.ok(!/data-registration-link|docs.google.com\/forms|drive.google.com/.test(landing));
assert.ok(landing.includes('youtube.com/watch?v=SQ4VtvYf8E4'));
const hero = landing.slice(landing.indexOf('<section class="hero"'), landing.indexOf('<section class="question-band"'));
for (const target of ['https://www.youtube.com/watch?v=SQ4VtvYf8E4', 'materialy.html', 'prepis.html']) assert.ok(hero.includes(`href="${target}"`));
assert.equal((hero.match(/class="resource-card(?: resource-card--video)?"/g) || []).length, 3);
assert.ok(hero.includes('id="registrace"'));
assert.ok(!/18:00|19:30|20:00|Registrace jsou uzavřené/.test(hero));
assert.ok(landing.indexOf('class="resource-grid"') < landing.indexOf('class="guest-band"'));
for (const t of [968, 2135, 2928, 4479, 5173, 5914]) assert.ok(landing.includes(`&amp;t=${t}s`));
const css = fs.readFileSync(path.join(root, 'live/vibe-coding/styles.css'));
const cssVersion = require('node:crypto').createHash('sha256').update(css).digest('hex').slice(0, 7);
assert.ok(landing.includes(`/live/vibe-coding/styles.css?v=${cssVersion}`));

const txt=fs.readFileSync(path.join(root,event.detail_url,'prepis.txt'),'utf8');
const transcript=fs.readFileSync(path.join(root,event.detail_url,'prepis.html'),'utf8');
const blocks=[...txt.matchAll(/^\[(\d\d:\d\d:\d\d)\] (.*)$/gm)];
assert.ok(blocks.length>200);
for(const [,time,text] of blocks){
 const sec=time.split(':').reduce((n,x)=>n*60+Number(x),0);
 assert.ok(transcript.includes(`id="t${sec}"`));
 assert.ok(transcript.includes(context.esc(text)), `Missing original utterance at ${time}`);
}
assert.match(transcript,/Automatický přepis bez\s*úplné kontroly poslechem/);
assert.match(transcript,/Mluvčí nejsou rozlišeni ani přiřazeni/);
const materials=fs.readFileSync(path.join(root,event.detail_url,'materialy.html'),'utf8');
assert.ok(materials.includes('Alex Trejtnar'));
assert.ok(!/<(?:script|form|iframe|object|embed)\b|\son\w+\s*=/i.test(materials));
const {projectEvent}=require('../tools/event-card-model.js');
assert.ok(projectEvent(event).description.includes('Záznam rozhovoru'));
assert.ok(landing.includes(projectEvent(event).description));
console.log(`PASS: recording, safe labeled links, closed registration, static materials, ${blocks.length} unchanged timestamped transcript blocks`);
